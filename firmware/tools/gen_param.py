#!/usr/bin/env python3
"""
madflight parameter header generator.

Regenerates ``<param.yaml>.h`` from ``<param.yaml>``. This is a standalone
version of madflight's ``extras/scripts/param_generator.py`` (the upstream
generator is a PlatformIO pre-script). It can be run directly::

    python3 tools/gen_param.py [path/to/param.yaml]

It is also wired into ``platformio.ini`` as a pre-build step (see
``tools/pre_gen_param.py``), so the header is always in sync with the yaml
file.
"""

import os
import sys

try:
    import yaml
except ImportError:
    sys.exit("error: pyyaml is required, install it with: pip install pyyaml")


def mf_options(p, g_enum):
    """Build the comma separated "mf_" prefixed option list of a parameter."""
    if "options" in p:
        return "mf_" + ",mf_".join(p["options"])
    elif "enum" in p:
        return "mf_" + ",mf_".join(g_enum[p["enum"]]["options"])
    else:
        return ""


def generate_config(outfilename, y):
    """Write the generated parameter header to outfilename."""
    g_enum = {}
    with open(outfilename, "w") as f:
        param = y["param"]  # required

        f.write("// DO NOT EDIT - GENERATED BY extras/scripts/param_generator.py\n")
        f.write("\n")
        f.write("#pragma once\n")
        f.write("\n")
        f.write("#include <stdint.h>\n")
        f.write("\n")

        # dump global enums
        enum = y.get("enum")  # optional
        if enum:
            g_enum = enum
            f.write("// Global enums\n")
            for k in enum:
                e = enum[k]
                f.write(f"{e['datatype']} {{ {mf_options(e, g_enum)} }};\n")
            f.write("\n")

        # start namespace
        f.write("namespace Cfg {\n")

        # dump parameter count
        f.write(f"  const uint16_t param_cnt = {len(param)}; //number of parameters\n")
        f.write("\n")

        # dump local enums
        f.write(
            "  //enums for madflight library parameters (prefixed with 'mf_' to prevent"
            " macro expansion of global #defines like ADC or ICM45686)\n"
        )
        for k in param:
            p = param[k]
            if p["type"] == "e":
                if "enum" not in p:
                    # local enum
                    f.write(f"  enum class {k}_enum : uint32_t {{ {mf_options(p, g_enum)} }};\n")
                    p["datatype"] = f"Cfg::{k}_enum"
                    p["default"] = f"Cfg::{k}_enum::mf_" + str(p["default"])
                else:
                    # global enum
                    p["datatype"] = f"{p['enum']}"
                    p["default"] = f"{p['enum']}::mf_" + str(p["default"])
        f.write("\n")

        # dump parameter lookup table
        f.write("  //list of parameters\n")
        f.write("  struct param_list_t {\n")
        f.write("    const char* name;\n")
        f.write("    const float defval;\n")
        f.write("    const char type;\n")
        f.write("    const char* options;\n")
        f.write("  };\n")
        f.write("  const param_list_t param_list[] = {\n")
        for k in param:
            p = param[k]
            f.write(
                f'    {{ "{k}", (float){p["default"]}, \'{p["type"]}\','
                f' "{mf_options(p, g_enum)}" }},\n'
            )
        f.write("  }; //const param_list_t param_list[]\n")

        # close namespace
        f.write("}; //namespace Cfg\n")
        f.write("\n")

        # dump parameters
        f.write("//all parameters with defaults\n")
        f.write("struct CfgParam {\n")
        for k in param:
            p = param[k]
            if "since" in p:
                f.write(f"  // {p['since']}\n")
            comment = ""
            if "comment" in p:
                comment = f" /* {p['comment']} */"
            f.write(f"  {p['datatype']} {k} = {p['default']};{comment}\n")
        f.write("}; //struct CfgParam\n")


def generate(param_yaml):
    """Generate the header for the given param.yaml file, returns the path."""
    param_yaml = os.path.abspath(param_yaml)
    with open(param_yaml) as stream:
        y = yaml.safe_load(stream)
    outfilename = param_yaml + ".h"
    generate_config(outfilename, y)
    print("generated %s" % outfilename)
    return outfilename


def main():
    if len(sys.argv) > 1:
        filename = sys.argv[1]
    else:
        here = os.path.dirname(os.path.abspath(__file__))
        filename = os.path.join(here, "..", "..", "madflight", "src", "cfg", "param.yaml")
    generate(filename)


if __name__ == "__main__":
    main()
